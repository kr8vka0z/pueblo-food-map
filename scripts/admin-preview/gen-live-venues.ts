// scripts/admin-preview/gen-live-venues.ts — writes live-venues.sql: copies of a few places from the repo's own
// published snapshot (src/data/published-venues.ts, already public) for the LOCAL preview database, so the
// Places tab can show "Live" (D1 equals the snapshot exactly) and "Live · edits waiting" (one field changed).
// WHY copies and not made-up rows: "Live" is decided by comparing D1 to that snapshot file, and the preview
// must not edit tracked files, so only rows that already sit in the snapshot can read as Live.
// Run by start.sh; the output goes to the gitignored .wrangler/admin-preview/, never committed.
// Usage: bun gen-live-venues.ts <repo root> <out.sql>
import { writeFileSync } from "node:fs";

const [repo, out] = process.argv.slice(2);
const { publishedVenues } = await import(`${repo}/src/data/published-venues.ts`);

const q = (v: unknown) => (v === undefined || v === null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const tri = (v: unknown) => (v === undefined || v === null ? "NULL" : v ? "1" : "0");
const json = (v: unknown) => (v === undefined || v === null ? "NULL" : q(JSON.stringify(v)));

// Two exact copies (Live) and two with a made-up local edit (Live · edits waiting). Non-box places only.
const pool = publishedVenues.filter((v: { category: string }) => v.category !== "blessing_box");
const picks = [pool[0], pool[1], pool[2], pool[3]].filter(Boolean);
const lines: string[] = ["-- generated by gen-live-venues.ts — do not edit by hand", ""];
const ids = picks.map((v: { id: string }) => q(v.id)).join(", ");
lines.push(`DELETE FROM venues WHERE id IN (${ids});`);
picks.forEach((v: Record<string, unknown>, i: number) => {
  const edited = i >= 2;
  const notes = edited ? "Preview only: this note was changed locally so the place reads as edits waiting." : v.notes;
  lines.push(
    "INSERT INTO venues (id, name, category, lat, lng, address, hours_weekly, hours_irregular, accepts_snap, accepts_wic, phone, email, url, notes, operator, source, last_verified, status, source_type, outside_county, created_at, created_by, updated_at, updated_by, published_at, published_by) VALUES (" +
      [
        q(v.id), q(v.name), q(v.category), q(v.lat), q(v.lng), q(v.address), json(v.hours_weekly), json(v.hours_irregular),
        tri(v.accepts_snap), tri(v.accepts_wic), q(v.phone), q(v.email), q(v.url), q(notes), q(v.operator), q(v.source), q(v.last_verified),
        "'published'", "'manual'", "0",
        "strftime('%Y-%m-%dT%H:%M:%fZ','now','-60 days')", "'preview-seed'",
        edited ? "strftime('%Y-%m-%dT%H:%M:%fZ','now','-1 days')" : "strftime('%Y-%m-%dT%H:%M:%fZ','now','-20 days')", "'preview-seed'",
        "strftime('%Y-%m-%dT%H:%M:%fZ','now','-16 days')", "'preview-seed'",
      ].join(", ") +
      ");",
  );
});
writeFileSync(out, lines.join("\n") + "\n");
console.log(`live-venues.sql: ${picks.map((v: { id: string }) => v.id).join(", ")}`);
